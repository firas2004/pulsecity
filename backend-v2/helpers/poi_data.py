def _enrich(poi: Dict, lat=None, lng=None) -> Dict:
    """Enrichit un POI avec calculs dynamiques."""
    enriched = dict(poi)
    cat = CATEGORIES.get(poi.get("category", ""), {})
    enriched["category_emoji"] = cat.get("emoji", "📍")
    enriched["category_color"] = cat.get("color", "#607D8B")
    enriched["category_display"] = cat.get("name", poi.get("category", ""))

    # Photo depuis le dossier /assests/
    poi_id = poi.get("id", "")
    if poi_id in POI_IMAGE_MAP:
        enriched["photo_url"] = POI_IMAGE_MAP[poi_id]
    elif poi.get("photo_url"):
        enriched["photo_url"] = poi["photo_url"]
    else:
        enriched["photo_url"] = "/assests/Tunis.png"

    # Distance
    if lat is not None and lng is not None:
        dist = _haversine_km(lat, lng, poi["lat"], poi["lng"])
        enriched["distance_km"] = round(dist, 2)
        enriched["walk_min"]    = round(dist / 5 * 60)
        enriched["car_min"]     = round(dist / 40 * 60)
    else:
        enriched["distance_km"] = None
        enriched["walk_min"]    = None
        enriched["car_min"]     = None

    return enriched


def load_all_pois(lat=None, lng=None) -> List[Dict]:
    return [_enrich(p, lat, lng) for p in POIS]


def get_nearby_pois(lat: float, lng: float, radius_km=5.0, category=None, limit=20) -> List[Dict]:
    results = []
    for poi in POIS:
        dist = _haversine_km(lat, lng, poi["lat"], poi["lng"])
        if dist > radius_km:
            continue
        if category and poi.get("category") != category:
            continue
        enriched = _enrich(poi, lat, lng)
        results.append(enriched)
    results.sort(key=lambda x: x["distance_km"])
    return results[:limit]


def get_emblematic_pois(governorate=None, limit=10) -> List[Dict]:
    results = [p for p in POIS if p.get("is_emblematic")]
    if governorate:
        results = [p for p in results if p.get("governorate", "").lower() == governorate.lower()]
    results.sort(key=lambda x: -(x.get("rating") or 0))
    return [_enrich(p) for p in results[:limit]]


def get_must_see_pois() -> List[Dict]:
    return [_enrich(p) for p in POIS if p.get("must_see")]
